import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDirectory = path.dirname(fileURLToPath(import.meta.url))
const rootDirectory = path.resolve(scriptsDirectory, '..')
const manifestPath = path.join(
  rootDirectory,
  'src/data/pokemon-sprite-manifest.json',
)
const outputPath = path.join(
  rootDirectory,
  'src/data/pokemon-sprite-availability.ts',
)

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const availability = {}

const fields = [
  ['home', null, 'normal'],
  ['home', null, 'shiny'],
  ['home', null, 'female'],
  ['home', null, 'shinyFemale'],
  ['genV', 'front', 'normal'],
  ['genV', 'front', 'shiny'],
  ['genV', 'front', 'female'],
  ['genV', 'front', 'shinyFemale'],
  ['genV', 'back', 'normal'],
  ['genV', 'back', 'shiny'],
  ['genV', 'back', 'female'],
  ['genV', 'back', 'shinyFemale'],
]

for (const [formId, entry] of Object.entries(manifest.sprites || {})) {
  let mask = 0
  fields.forEach(([family, direction, variant], bit) => {
    const group = direction ? entry?.[family]?.[direction] : entry?.[family]
    if (group?.[variant]) mask |= 1 << bit
  })
  if (mask > 0) availability[formId] = mask
}

const content = `// Generated by scripts/generate-compact-manifests.mjs.
// Each number is a 12-bit availability mask; sprite URLs are deterministic.
export const POKEMON_SPRITE_FALLBACK_FORM_ID = ${JSON.stringify(
  manifest.fallbackFormId || '201',
)}
export const pokemonSpriteAvailability: Readonly<Record<string, number>> = ${JSON.stringify(
  availability,
)}
`

fs.writeFileSync(outputPath, content)
console.log(
  `Wrote ${path.relative(rootDirectory, outputPath)} (${Object.keys(availability).length} forms)`,
)
